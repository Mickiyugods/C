import { readFileSync, writeFileSync } from "node:fs";

// Copies the ABIs of the compiled contracts into src/lib/abis.ts so the site never drifts from the code.
// Run after `forge build` in ../contracts:  node scripts/sync-abis.mjs
const out = new URL("../../contracts/out/", import.meta.url);
const names = ["Launcher", "CollectionRegistry", "Vault", "FeeRouter", "RaffleDistributor"];

const extra = {
  ponsCurve: [
    "function getReserves() view returns (uint256 quoteReserve, uint256 tokenReserve)",
    "function realQuoteReserve() view returns (uint256)",
    "function graduationThreshold() view returns (uint256)",
    "function readyToGraduate() view returns (bool)",
    "function sellableTokens() view returns (uint256)",
    "function feeBps() view returns (uint256)",
    "function creatorTaxBps() view returns (uint256)",
    "function buy(uint256 quoteIn, uint256 minTokensOut, address recipient) payable returns (uint256)",
    "function sell(uint256 tokensIn, uint256 minQuoteOut, address recipient) returns (uint256)",
    "event CurveBuy(address indexed buyer, address indexed recipient, uint256 quoteIn, uint256 tokensOut, uint256 fee, uint256 tax)",
    "event CurveSell(address indexed seller, address indexed recipient, uint256 tokensIn, uint256 quoteOut, uint256 fee, uint256 tax)",
  ],
  erc20: [
    "function name() view returns (string)",
    "function symbol() view returns (string)",
    "function decimals() view returns (uint8)",
    "function totalSupply() view returns (uint256)",
    "function balanceOf(address) view returns (uint256)",
    "function allowance(address owner, address spender) view returns (uint256)",
    "function approve(address spender, uint256 value) returns (bool)",
    "event Transfer(address indexed from, address indexed to, uint256 value)",
  ],
  erc721: [
    "function ownerOf(uint256) view returns (address)",
    "function balanceOf(address) view returns (uint256)",
    "function name() view returns (string)",
    "function symbol() view returns (string)",
    "function tokenURI(uint256) view returns (string)",
  ],
};

let src = "// Generated by scripts/sync-abis.mjs from the compiled contracts. Do not edit by hand.\n\n";
for (const n of names) {
  const json = JSON.parse(readFileSync(new URL(`${n}.sol/${n}.json`, out), "utf8"));
  const abi = json.abi.filter((i) => i.type !== "constructor");
  const key = n.charAt(0).toLowerCase() + n.slice(1) + "Abi";
  src += `export const ${key} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
src += `import { parseAbi } from "viem";\n\n`;
for (const [k, lines] of Object.entries(extra)) {
  src += `export const ${k}Abi = parseAbi(${JSON.stringify(lines, null, 2)});\n\n`;
}
writeFileSync(new URL("../src/lib/abis.ts", import.meta.url), src);
console.log("wrote src/lib/abis.ts for", names.join(", "));
