import { readFileSync, writeFileSync } from "node:fs";

// Copies the ABIs of the compiled contracts into src/abis.mjs. Run after `forge build` in ../contracts.
const out = new URL("../../contracts/out/", import.meta.url);
const names = ["Launcher", "CollectionRegistry", "Vault", "FeeRouter", "RaffleDistributor"];

let src = "// Generated by scripts/sync-abis.mjs from the compiled contracts. Do not edit by hand.\nimport { parseAbi } from \"viem\";\n\n";
for (const n of names) {
  const json = JSON.parse(readFileSync(new URL(`${n}.sol/${n}.json`, out), "utf8"));
  const abi = json.abi.filter((i) => i.type !== "constructor");
  src += `export const ${n.charAt(0).toLowerCase() + n.slice(1)}Abi = ${JSON.stringify(abi, null, 2)};\n\n`;
}
src += `export const ponsCurveAbi = parseAbi([
  "function getReserves() view returns (uint256 quoteReserve, uint256 tokenReserve)",
  "function sellableTokens() view returns (uint256)",
]);

export const erc20Abi = parseAbi([
  "function totalSupply() view returns (uint256)",
  "function balanceOf(address) view returns (uint256)",
  "event Transfer(address indexed from, address indexed to, uint256 value)",
]);

export const feeEscrowAbi = parseAbi(["function balanceOf(address recipient) view returns (uint256)"]);
`;
writeFileSync(new URL("../src/abis.mjs", import.meta.url), src);
console.log("wrote src/abis.mjs");
